"""산지니(또는 다른 캐릭터) PNG를 메인 화면 가우시안용 데이터로 바꿉니다.

사용법:  python3 tools/make_mascot_data.py images/logo/sanjini.png
결과:    assets/js/mascot-data.js

브라우저가 그림을 직접 읽을 수 없는 환경(미리보기 창 등)을 위한 예비 데이터입니다.
실제 GitHub Pages 사이트에서는 그림 파일만 바꿔도 되지만, 그림을 바꾸면 이 스크립트도 한 번 실행해 두세요.
"""
import base64, sys
from PIL import Image

SH = 140  # main.js 의 SH 와 같아야 합니다
src = sys.argv[1] if len(sys.argv) > 1 else "images/logo/sanjini.png"
im = Image.open(src).convert("RGBA")
SW = max(1, round(im.width / im.height * SH))
small = im.resize((SW, SH), Image.LANCZOS)
b64 = base64.b64encode(small.tobytes()).decode()
with open("assets/js/mascot-data.js", "w") as f:
    f.write("/* generated by tools/make_mascot_data.py from %s */\n" % src)
    f.write('window.CVSP_MASCOT = {w: %d, h: %d, rgba: "%s"};\n' % (SW, SH, b64))
print("wrote assets/js/mascot-data.js", SW, SH)
